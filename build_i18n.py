def build(idx, lang):
    s = src
    for t in T:
        s = s.replace(t[0], t[idx])
    # шляхи та мовний перемикач
    s = s.replace('src="img/', 'src="../img/')
    s = re.sub(r'<div class="lang" id="lang">.*?</div>',
        '<div class="lang" id="lang"><a href="../">RU</a><a href="../ua/"%s>UA</a><a href="../en/"%s>EN</a></div>'
        % (' class="on"' if lang=='ua' else '', ' class="on"' if lang=='en' else ''), s, flags=re.S)
    s = s.replace('<meta name="theme-color"', '<link rel="alternate" hreflang="ru" href="../"><link rel="alternate" hreflang="uk" href="../ua/"><link rel="alternate" hreflang="en" href="../en/">\n<meta name="theme-color"')
    out = root / lang
    out.mkdir(exist_ok=True)
    (out / 'index.html').write_text(s, encoding='utf-8')
    return s

